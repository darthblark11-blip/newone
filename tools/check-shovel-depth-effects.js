// Blood, dust and hit effects must recede with a descending figure while the
// surface blood cache and normal particle painter keep their original scale.
const assert = require('assert');
const {probe: P} = require('./harness');
let checks = 0;
function ok(value, label) { assert.ok(value, label); checks++; }
P(`currentLevel=1;currentBiome=1;BIOME_ACTIVE=true;doTick=true;
width=940;height=900;viewLeft=0;viewRight=940;viewTop=0;viewBottom=900;
shovelExcavation={};shovelMakeCell(5,7,240,true);
player=new Character(528,720,true);player.shovelLevel=1;player.shovelDepth=0;player.shovelDepthTarget=240;
particles=[];wipeAllBloodBanks();useBloodBank('effects-home');
__scales=[];__painted=0;__p5Depth=0;__canvasDepth=0;
__nativeScale=scale;scale=function(...a){__scales.push(a[0]);__nativeScale(...a);};
__nativePush=push;__nativePop=pop;push=function(){__p5Depth++;__nativePush();};pop=function(){__p5Depth--;__nativePop();};
drawingContext.save=function(){__canvasDepth++;};drawingContext.restore=function(){__canvasDepth--;};
__effect=newParticle(548,723,color(90,0,0),'BLOOD',4,1,player);
__effect.paint=function(){__painted++;};__effect.show();`);
ok(P('__scales.length===0&&__painted===1'), 'An owned effect starts at normal surface scale');
const sizes=[];
for (const d of [1,18,60,140,240]) {
  P(`player.shovelDepth=${d};__scales=[];__effect.show();__projection=shovelEffectProjection(__effect);__actorProjection=shovelActorProjection(player);`);
  sizes.push(P('__projection.scale'));
  ok(P('Math.abs(__projection.scale-shovelRenderScale(player))<1e-9'), 'Blood uses current actor scale at depth '+d);
  ok(P('Math.abs(__projection.x-__actorProjection.x-20*__projection.scale)<1e-9&&Math.abs(__projection.y-__actorProjection.y-3*__projection.scale)<1e-9'), 'Effect origin and offset share the actor perspective at depth '+d);
}
ok(sizes.every((v,i,a)=>!i||v<a[i-1]), 'Effects shrink continuously throughout the descent');
ok(P('__effect.x===548&&__effect.y===723&&__effect.sz>0'), 'Rendering does not rewrite particle simulation coordinates or size');
ok(P('__p5Depth===0&&__canvasDepth===0'), 'Repeated pit particle painting balances native and p5 stacks');
P(`__effect.update();__projection=shovelEffectProjection(__effect);`);
ok(P('Math.abs(__projection.x-__actorProjection.x-(__effect.x-player.x)*__projection.scale)<1e-9'), 'Particle travel distance recedes along with its footprint');
P(`__oldOwner=new Character(528,720,false,'NORMAL');__oldOwner.shovelLevel=1;__oldOwner.shovelDepth=60;
__beforeDeathEffect=newParticle(528,720,color(90,0,0),'BLOOD',0,0,__oldOwner);
__oldOwner.shovelEffectBody={x:528,y:720,shovelLevel:1,shovelDepth:140};`);
ok(P('shovelEffectDepth(__beforeDeathEffect)===140'), 'Pre-death blood follows a corpse that continues falling after its source actor is removed');
P(`__surface=newParticle(548,723,color(90,0,0),'BLOOD');__surface.paint=function(){__painted++;};__scales=[];__surface.show();`);
ok(P('__scales.length===0&&shovelEffectDepth(__surface)===0'), 'A separate surface effect above a shaft does not inherit a nearby actor depth');
P(`_particlePool.push(__effect);__reused=newParticle(528,720,color(80),'SMOKE');`);
ok(P('__reused===__effect&&__reused.shovelOwner===null&&shovelEffectDepth(__reused)===0'), 'Pooled particles shed their previous falling owner on reuse');
P(`spawnSplatter(player.x,player.y,'BLOOD',color(90,0,0),player);`);
ok(P('shovelBloodMarks.length===1&&bloodPools.length===0&&Object.keys(bloodChunks).length===0'), 'Underground blood never allocates or stains a surface blood texture');
P(`__mark=shovelBloodMarks[0];for(let i=0;i<24;i++)updateBloodPools();__scales=[];drawShovelBloodMarks();`);
ok(P('__scales.some(s=>Math.abs(s-shovelRenderScale(player))<1e-9)'), 'Pit blood pools use the same depth scale as the body');
P(`player.shovelDepth=0;player.shovelDepthTarget=0;updateBloodPools();`);
ok(P('shovelEffectDepth(__mark)===240&&__mark.shovelOwner===null'), 'Deposited blood stays on its floor when its living owner climbs out');
P(`__roof=shovelMakeCell(6,7,240,false);__roof.ceiling=18;
__hiddenOwner=new Character(624,720,false,'NORMAL');__hiddenOwner.shovelLevel=1;__hiddenOwner.shovelDepth=240;
__hidden=newParticle(624,720,color(90,0,0),'BLOOD',0,0,__hiddenOwner);__hidden.paint=function(){__painted++;};__beforePaint=__painted;__hidden.show();`);
ok(P('__painted===__beforePaint'), 'An intact roof hides deep particles from a surface player');
P(`player.x=624;player.y=720;player.shovelDepth=240;__hidden.show();`);
ok(P('__painted===__beforePaint+1'), 'A player in the same tunnel can see its local particles');
ok(P('__p5Depth===0&&__canvasDepth===0'), 'Roof clipping restores both graphics stacks');
P(`player.shovelDepthTarget=240;spawnSplatter(624,720,'BLOOD',color(90,0,0),player);
__scales=[];drawShovelBloodMarks();`);
ok(P('__scales.length===1'), 'Roofed blood does not paint over intact terrain in the open pit pass');
P(`__scales=[];drawShovelBloodMarks(player);`);
ok(P('__scales.length===1'), 'Roofed blood paints inside the matching actor cutaway');
P(`useBloodBank('effects-away');`);
ok(P('shovelBloodMarks.length===0'), 'Travel does not carry pit blood into another biome');
P(`useBloodBank('effects-home');`);
ok(P('shovelBloodMarks.length===2&&shovelBloodMarks[0]===__mark'), 'Returning restores the same pit blood with its original floor depth');
P(`player.x=528;player.y=720;player.shovelDepth=240;player.shovelDepthTarget=240;
for(let i=0;i<SHOVEL_BLOOD_MARK_MAX+4;i++)spawnSplatter(528,720,'BLOOD',color(90,0,0),player);`);
ok(P('shovelBloodMarks.length===SHOVEL_BLOOD_MARK_MAX'), 'Repeated deep blood effects retain a fixed small mark budget');
P(`__corpse=new Corpse(528,720,0,0,color(120),color(30),0,0,[],WEAPONS.PISTOL,0,'NORMAL',21,27,player);
particles=[];__corpse.bT=7;__corpse.dT=1;__corpse.bloodTimer=0;__corpse.smokeTimer=0;__corpse.fatalSpray=null;__corpse.update();`);
ok(P('particles.length>0&&particles.every(p=>p.shovelOwner===__corpse&&shovelEffectDepth(p)===240)'), 'Native corpse bleeding retains the body depth after the original actor is gone');
P(`delete player.shovelEffectBody;shovelDigParticles=[];player.shovelDepth=18;player.shovelDigKind='DOWN';shovelEmitDigParticles(player);
player.shovelDepth=240;__scales=[];shovelDrawDigParticles(240,player);`);
ok(P('__scales.length===18&&__scales.every(s=>s<1)'), 'Dig clods and dust continue shrinking rather than freezing at their emitted scale');
P(`__contact=boxingEmitContactEffect({outcome:'HIT',point:{x:538,y:720},attacker:player,defender:player});
__scales=[];boxingDrawContactEffects([__contact]);`);
ok(P('__contact.shovelOwner===player&&__scales.some(s=>Math.abs(s-shovelRenderScale(player))<1e-9)'), 'Comic punch impact bursts recede with their victim too');
P(`wipeAllBloodBanks();`);
ok(P('shovelBloodMarks.length===0'), 'A new game clears all pit blood marks');
P(`scale=__nativeScale;push=__nativePush;pop=__nativePop;`);
console.log('Shovel depth effects: '+checks+' checks passed');
