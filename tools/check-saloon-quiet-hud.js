// Exercise the real HUD paint and contextual door actions, without hiding
// usable controls or refreshing the overlay for ordinary combat contacts.
const assert = require('assert');
const {ctx, probe} = require('./harness');
let count = 0;
const check = (code, label) => { assert.ok(probe(code), label); count++; };
function capture() {
  const seen = [], original = ctx.text;
  ctx.text = (label, x, y) => {
    seen.push(String(label));
    if (String(label).startsWith('GRIT ')) seen.gritPosition = {x, y};
  };
  try { probe('drawFrontierSaloonHud();'); } finally { ctx.text = original; }
  return seen;
}
probe(`isStoryMode=false;resetStoryProgress();startAtLevel(3);started=true;
  isPaused=isDead=isWin=killcamMode=false;doTick=true;
  inTownCutscene=inFarmCutscene=inFarmPostCutscene=inFortCutscene=inPostAmbushCutscene=false;
  inWorldBuildingMenu=inOverworldView=inTravelMenu=inStoryIntro=inDarchonCall=false;
  leftStick={active:false,dx:0,dy:0};rightStick={active:false,dx:0,dy:0,dist:0};
  window.isDesktop=false;window.showOnScreenControls=true;enterFrontierSaloon();
  var hudScene=_frontierSaloonSession;`);
check('frontierSaloonCanLeave()&&frontierSaloonButtons().some(b=>b.action==="EXIT")', 'The actual entry door offers leaving while freely exploring');
probe('player.x=250;');
check('!frontierSaloonCanLeave()&&!frontierSaloonButtons().some(b=>b.action==="EXIT")', 'Leaving disappears away from the actual doorway');
check('!frontierSaloonAction("EXIT")&&frontierSaloonIsInside()', 'A stale leave action cannot exit from the middle of the room');
probe('startFrontierSaloonBrawl();');
check('!frontierSaloonButtons().some(b=>b.action==="EXIT")', 'The active fight has no leave button');
probe('player.x=FRONTIER_SALOON_ROOM.door.x;player.y=FRONTIER_SALOON_ROOM.door.y;');
check('!frontierSaloonCanLeave()&&!interactFrontierSaloonActivity()&&frontierSaloonIsInside()', 'Walking to the door during the fight cannot escape through interaction');
check('!frontierSaloonAction("EXIT")', 'The gamepad leave path shares the same active-fight restriction');
let seen = capture();
assert(seen.some(t=>t.startsWith('GRIT '))&&seen.some(t=>t.startsWith('HEALTH ')));count++;
assert(seen.gritPosition.x < ctx.width / 3 && seen.gritPosition.y === 22,
  'GRIT has its own upper-left bar outside the fading information header');count++;
probe('hudScene.elapsedMs+=3500;');
check('frontierSaloonHudAlpha(hudScene)===1', 'Status panels remain fully readable for 3.5 seconds');
probe('hudScene.elapsedMs+=200;');
check('Math.abs(frontierSaloonHudAlpha(hudScene)-.5)<.000001', 'The last 400 milliseconds smoothly fade rather than popping away');
probe('hudScene.elapsedMs+=200;');
seen = capture();
assert(seen.includes('GRIT 100/100')&&!seen.some(t=>/^HEALTH |^COPPER SPUR |^BARROOM PEACEMAKER /.test(t)));count++;
assert(!seen.includes('TAP HEAD')&&!seen.includes('HOLD → RELEASE BODY'));count++;
assert(seen.includes('L STRAIGHT')&&seen.includes('R JAB')&&seen.includes('GUARD')&&seen.includes('FOOTWORK'));count++;
probe('hudScene.grit=53;player.hp=Math.max(1,player.hp-3);hudScene.hitMs=160;player._boxing.guardSector="N";');
check('frontierSaloonHudAlpha(hudScene)===0', 'Damage and changing guard do not keep the text panels permanently visible');
assert(capture().includes('GRIT 53/100'),'Combat health updates immediately while the text panel remains faded');count++;
probe('hudScene.fighters[0].knockedOut=true;');
check('frontierSaloonHudAlpha(hudScene)===1', 'A downed opponent briefly reveals the new progress');
probe('hudScene.elapsedMs+=3900;window.isDesktop=true;window.showOnScreenControls=false;');
seen = capture();
assert(!seen.some(t=>t.startsWith('E / R · STRAIGHT')||t.startsWith('ARROWS / IJKL')));count++;
probe('isPaused=true;var hudPauseTime=hudScene.elapsedMs;');
for(let i=0;i<10;i++) probe('updateFrontierSaloonActivity();');
check('hudScene.elapsedMs===hudPauseTime', 'Pause freezes the overlay lifetime');
seen = capture();
assert(seen.includes('PAUSED')&&seen.includes('RESUME')&&seen.includes('SAVE GAME')&&seen.includes('LEAVE & OPEN SHOP'));count++;
probe('isPaused=false;hudScene.brawl="KNOCKOUT";');
check('!frontierSaloonCanLeave()&&!frontierSaloonButtons().some(b=>b.action==="EXIT")&&!interactFrontierSaloonActivity()', 'The player fall cannot expose or activate the doorway exit');
seen = capture();
assert(seen.includes('KNOCKED OUT · CATCH YOUR BREATH')&&!seen.includes('MOVE')&&!seen.includes('FOOTWORK'));count++;
probe('hudScene.brawl="LOST";player.x=FRONTIER_SALOON_ROOM.counter.x;player.y=FRONTIER_SALOON_ROOM.counter.y;interactFrontierSaloonActivity();');
seen = capture();
assert(seen.includes('MAE’S SIDE MISSIONS')&&seen.includes('1 · BARROOM PEACEMAKER')&&seen.includes('2 · QUICK DRAW DUEL'));count++;
probe('startFrontierQuickDraw();');capture();
probe('hudScene.elapsedMs+=3900;hudScene.duel.phase="DRAW";');
check('frontierSaloonHudAlpha(hudScene)===1', 'The green draw cue refreshes the faded duel panels');
probe('hudScene.duel.phase="RESULT";hudScene.duel.won=true;hudScene.duel.result="YOU DREW FIRST";');
capture();probe('hudScene.elapsedMs+=3900;');seen=capture();
assert(!seen.includes('YOU WIN')&&seen.includes('NEXT CHALLENGER')&&seen.includes('BACK TO SALOON'));count++;
check('!frontierSaloonButtons().some(b=>b.action==="EXIT")&&!frontierSaloonAction("EXIT")', 'Duel results return to the saloon before any doorway exit');
probe('frontierSaloonAction("BACK");');
check('!frontierSaloonButtons().some(b=>b.action==="EXIT")', 'Returning to Mae does not offer a remote leave shortcut');
probe('frontierSaloonNotify("A BRIEF NOTICE");var toastPauseMs=_frontierSaloonToastMs;isPaused=true;');
for(let i=0;i<10;i++) probe('updateFrontierSaloonActivity();');
check('_frontierSaloonToastMs===toastPauseMs', 'Pause also freezes notice lifetime');
probe('isPaused=false;deltaTime=100;');
for(let i=0;i<36;i++) probe('updateFrontierSaloonActivity();');
check('_frontierSaloonToastMs===300&&frontierSaloonHudFade(3900-_frontierSaloonToastMs)<1', 'Notices enter their fade after the same 3.5-second hold');
for(let i=0;i<3;i++) probe('updateFrontierSaloonActivity();');
check('_frontierSaloonToastMs===0', 'Expired notices are removed entirely');
probe('player.x=FRONTIER_SALOON_ROOM.door.x;player.y=FRONTIER_SALOON_ROOM.door.y;');
check('frontierSaloonAction("EXIT")&&!frontierSaloonIsInside()', 'Leaving works again at the actual door after the activity');
console.log(`Saloon quiet HUD: ${count} native paint and action checks passed.`);
